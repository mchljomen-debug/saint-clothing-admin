const addReportHeader=({
worksheet,
title,
subtitle,
endCol,
branchLabel="All Branches",
rangeLabel="All",
generatedAt=getGeneratedDate(),
exportedBy=getExportedBy()
})=>{
worksheet.mergeCells(1,1,1,endCol);

const titleCell=worksheet.getCell(1,1);
titleCell.value=title;
styleReportTitle(titleCell);
worksheet.getRow(1).height=30;

worksheet.mergeCells(2,1,2,endCol);

const subtitleCell=worksheet.getCell(2,1);
subtitleCell.value=subtitle;
styleReportSubtitle(subtitleCell);
worksheet.getRow(2).height=21;

const valueEndCol=Math.max(2,endCol);

worksheet.getCell(4,1).value="Branch";
styleMetaLabel(worksheet.getCell(4,1));

if(valueEndCol>=2){
worksheet.mergeCells(4,2,4,valueEndCol);
}

worksheet.getCell(4,2).value=formatBranchLabel(branchLabel);
styleMetaValue(worksheet.getCell(4,2));

worksheet.getCell(5,1).value="Range";
styleMetaLabel(worksheet.getCell(5,1));

if(valueEndCol>=2){
worksheet.mergeCells(5,2,5,valueEndCol);
}

worksheet.getCell(5,2).value=rangeLabel;
styleMetaValue(worksheet.getCell(5,2));

worksheet.getCell(6,1).value="Generated";
styleMetaLabel(worksheet.getCell(6,1));

if(valueEndCol>=2){
worksheet.mergeCells(6,2,6,valueEndCol);
}

worksheet.getCell(6,2).value=generatedAt;
styleMetaValue(worksheet.getCell(6,2));

worksheet.getCell(7,1).value="Exported By";
styleMetaLabel(worksheet.getCell(7,1));

if(valueEndCol>=2){
worksheet.mergeCells(7,2,7,valueEndCol);
}

worksheet.getCell(7,2).value=exportedBy;
styleMetaValue(worksheet.getCell(7,2));

worksheet.getRow(4).height=20;
worksheet.getRow(5).height=20;
worksheet.getRow(6).height=20;
worksheet.getRow(7).height=20;
};

const addSectionTitle=(worksheet,row,startCol,endCol,title)=>{
worksheet.mergeCells(row,startCol,row,endCol);

const cell=worksheet.getCell(row,startCol);
cell.value=title;
styleSectionTitle(cell);
worksheet.getRow(row).height=22;
};

const styleBodyCells=({
worksheet,
startRow,
endRow,
startCol,
totalCols,
numericColumns=[],
currencyColumns=[],
lowStockColumn=null,
statusColumn=null
})=>{
for(let rowIndex=startRow;rowIndex<=endRow;rowIndex++){
const alternate=(rowIndex-startRow)%2===1;

for(let index=0;index<totalCols;index++){
const absoluteCol=startCol+index;
const localCol=index+1;
const cell=worksheet.getCell(rowIndex,absoluteCol);

cell.font={
name:FONT_NAME,
size:10,
color:{argb:COLORS.black}
};

cell.alignment={
vertical:"middle",
horizontal:numericColumns.includes(localCol)||currencyColumns.includes(localCol)?"right":"left",
wrapText:true
};

cell.fill={
type:"pattern",
pattern:"solid",
fgColor:{argb:alternate?COLORS.softFill:COLORS.white}
};

applyBorder(cell);
}

if(lowStockColumn){
const stockCell=worksheet.getCell(
rowIndex,
startCol+lowStockColumn-1
);

const stockValue=Number(stockCell.value);

if(Number.isFinite(stockValue)){
if(stockValue<=2){
stockCell.fill={
type:"pattern",
pattern:"solid",
fgColor:{argb:COLORS.redFill}
};

stockCell.font={
name:FONT_NAME,
bold:true,
color:{argb:COLORS.redText}
};
}else if(stockValue<=5){
stockCell.fill={
type:"pattern",
pattern:"solid",
fgColor:{argb:COLORS.orangeFill}
};

stockCell.font={
name:FONT_NAME,
bold:true,
color:{argb:COLORS.orangeText}
};
}
}
}

if(statusColumn){
const statusCell=worksheet.getCell(
rowIndex,
startCol+statusColumn-1
);

const status=String(statusCell.value||"").trim().toLowerCase();

if(
status.includes("delivered")||
status.includes("completed")||
status.includes("paid")
){
statusCell.fill={
type:"pattern",
pattern:"solid",
fgColor:{argb:COLORS.greenFill}
};

statusCell.font={
name:FONT_NAME,
bold:true,
color:{argb:COLORS.greenText}
};
}else if(
status.includes("pending")||
status.includes("processing")||
status.includes("packing")||
status.includes("order placed")
){
statusCell.fill={
type:"pattern",
pattern:"solid",
fgColor:{argb:COLORS.orangeFill}
};

statusCell.font={
name:FONT_NAME,
bold:true,
color:{argb:COLORS.orangeText}
};
}else if(
status.includes("cancelled")||
status.includes("canceled")||
status.includes("failed")||
status.includes("rejected")
){
statusCell.fill={
type:"pattern",
pattern:"solid",
fgColor:{argb:COLORS.redFill}
};

statusCell.font={
name:FONT_NAME,
bold:true,
color:{argb:COLORS.redText}
};
}
}
}
};

const addDataTable=({
worksheet,
startRow,
startCol,
title,
headers,
rows,
numericColumns=[],
currencyColumns=[],
lowStockColumn=null,
statusColumn=null,
addFilter=true
})=>{
const safeRows=rows?.length
?rows
:[headers.map((_,index)=>index===0?"No data available":"")];

const totalCols=headers.length;
const endCol=startCol+totalCols-1;

addSectionTitle(
worksheet,
startRow,
startCol,
endCol,
title
);

const headerRowNumber=startRow+1;
const headerRow=worksheet.getRow(headerRowNumber);

headers.forEach((header,index)=>{
const cell=worksheet.getCell(
headerRowNumber,
startCol+index
);

cell.value=header;
styleHeaderCell(cell);
});

headerRow.height=24;

safeRows.forEach((row,rowIndex)=>{
row.forEach((value,colIndex)=>{
worksheet.getCell(
headerRowNumber+1+rowIndex,
startCol+colIndex
).value=value;
});
});

const bodyStart=headerRowNumber+1;
const bodyEnd=headerRowNumber+safeRows.length;

styleBodyCells({
worksheet,
startRow:bodyStart,
endRow:bodyEnd,
startCol,
totalCols,
numericColumns,
currencyColumns,
lowStockColumn,
statusColumn
});

currencyColumns.forEach((localCol)=>{
for(let row=bodyStart;row<=bodyEnd;row++){
worksheet.getCell(
row,
startCol+localCol-1
).numFmt='"₱"#,##0.00';
}
});

numericColumns.forEach((localCol)=>{
if(currencyColumns.includes(localCol))return;

for(let row=bodyStart;row<=bodyEnd;row++){
worksheet.getCell(
row,
startCol+localCol-1
).numFmt="#,##0";
}
});

if(addFilter){
worksheet.autoFilter={
from:{
row:headerRowNumber,
column:startCol
},
to:{
row:headerRowNumber,
column:endCol
}
};
}

return{
headerRow:headerRowNumber,
bodyStart,
bodyEnd,
endCol
};
};

