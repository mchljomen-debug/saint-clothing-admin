export const exportSingleDashboardSection=async({
sheetTitle,
fileName,
subtitle,
headers,
rows,
currencyColumns=[],
numberColumns=[],
lowStockColumn=null,
statusColumn=null
})=>{
const workbook=buildWorkbook();

const safeSheetTitle=String(sheetTitle||"Dashboard")
.replace(/[\\/*?:[\]]/g,"")
.slice(0,31)||"Dashboard";

const sheet=workbook.addWorksheet(safeSheetTitle,{
properties:{
tabColor:{argb:COLORS.gold}
}
});

const endCol=Math.max(headers.length,2);

const role=localStorage.getItem("role")||"";
const branch=localStorage.getItem("branch")||"";
const storedSelectedBranch=localStorage.getItem("selectedBranch")||"";

const branchLabel=role==="admin"
?storedSelectedBranch&&storedSelectedBranch!=="all"
?storedSelectedBranch
:"All Branches"
:branch||"All Branches";

addReportHeader({
worksheet:sheet,
title:`SAINT CLOTHING ${String(sheetTitle||"DASHBOARD").toUpperCase()} REPORT`,
subtitle:subtitle||"Saint Clothing Dashboard Export",
endCol,
branchLabel,
rangeLabel:subtitle||"Dashboard section"
});

const tableResult=addDataTable({
worksheet:sheet,
startRow:9,
startCol:1,
title:String(sheetTitle||"Dashboard").toUpperCase(),
headers,
rows,
numericColumns:numberColumns,
currencyColumns,
lowStockColumn,
statusColumn,
addFilter:true
});

autoFitColumns(sheet);

headers.forEach((header,index)=>{
const headerText=String(header||"").toLowerCase();
const column=sheet.getColumn(index+1);

if(
headerText.includes("product")||
headerText.includes("customer")
){
column.width=Math.max(column.width||0,24);
}

if(
headerText.includes("order id")||
headerText.includes("date")
){
column.width=Math.max(column.width||0,20);
}

if(headerText.includes("payment method")){
column.width=Math.max(column.width||0,18);
}
});

configureWorksheet({
worksheet:sheet,
lastRow:tableResult.bodyEnd,
lastCol:endCol
});

await saveWorkbook(
workbook,
fileName
);
};