const FONT_NAME="Arial";

const thinBorder={
top:{style:"thin",color:{argb:COLORS.border}},
left:{style:"thin",color:{argb:COLORS.border}},
bottom:{style:"thin",color:{argb:COLORS.border}},
right:{style:"thin",color:{argb:COLORS.border}}
};

const formatRangeLabel=(value)=>{
const labels={
today:"Today",
week:"This Week",
month:"This Month",
year:"This Year"
};
return labels[value]||String(value||"All");
};

const formatBranchLabel=(value)=>{
if(!value||String(value).toLowerCase()==="all")return"All Branches";
return String(value);
};

const getExportedBy=()=>{
return localStorage.getItem("adminName")||
localStorage.getItem("name")||
"Saint Clothing Admin";
};

const getGeneratedDate=()=>{
return new Date().toLocaleString("en-PH",{
year:"numeric",
month:"long",
day:"numeric",
hour:"numeric",
minute:"2-digit",
hour12:true
});
};

const sanitizeFileName=(value)=>{
return String(value||"all")
.trim()
.toLowerCase()
.replace(/[^a-z0-9]+/g,"-")
.replace(/^-+|-+$/g,"")||"all";
};

const columnNumberToName=(num)=>{
let name="";
while(num>0){
const remainder=(num-1)%26;
name=String.fromCharCode(65+remainder)+name;
num=Math.floor((num-1)/26);
}
return name;
};

const buildWorkbook=()=>{
const workbook=new ExcelJS.Workbook();

workbook.creator="Saint Clothing Admin";
workbook.lastModifiedBy=getExportedBy();
workbook.created=new Date();
workbook.modified=new Date();
workbook.company="Saint Clothing";
workbook.subject="Saint Clothing Dashboard Report";
workbook.title="Saint Clothing Dashboard Report";
workbook.description="Administrative dashboard report generated by Saint Clothing.";

return workbook;
};

const saveWorkbook=async(workbook,fileName)=>{
const buffer=await workbook.xlsx.writeBuffer();

const blob=new Blob([buffer],{
type:"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
});

saveAs(blob,fileName);
};

